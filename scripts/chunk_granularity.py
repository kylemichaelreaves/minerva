"""Gate chunk granularity: catch a parser that emitted a whole work as one chunk.

Corpus-wide the mean chunk is 377 characters, but 94 work/lang pairs are two
orders of magnitude coarser — Aeschylus's *Agamemnon* in English is a single
82,256-character chunk, the entire play. Those works cannot be retrieved at
passage granularity: one embedding vector covers the whole text, BM25 scores
it as one document, and any citation points at the work rather than a locus
(#176).

Shaped after ``chunk_count_validation`` deliberately, because the same two
environments have to be served:

* **Policy** lives in ``data/authors/manifest.yaml`` under ``granularity``:
  the two thresholds, and ``known_coarse`` — the hand-reviewed baseline of
  pairs that already exceed them.
* **Measurement** lives in the committed
  ``data/authors/chunk_granularity.json``, regenerated by
  ``make generate-authors``, because ``data/index.sqlite`` is gitignored and
  CI never builds it (#157).

The split is what makes the gate bite. Both files could be regenerated from
the DB, but then ``make generate-authors`` would silently bless every new
violation and the check would validate nothing. Only the measurement is
generated; the baseline is edited by hand, so admitting a newly-coarse work
is a visible line in a PR diff rather than a side effect of an ingest.

**The gate is baseline-pinned, and fails only on new violations.** A bare
"no chunk over N characters" assertion fails immediately on all 753 existing
ones and is unlandable — the trap that has #229 stuck.
"""

from __future__ import annotations

import dataclasses
import json
import sqlite3
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT_PATH = REPO_ROOT / "data" / "authors" / "chunk_granularity.json"

# Fallbacks used only when the manifest omits `granularity` entirely, so a
# manifest predating this gate still validates rather than crashing.
DEFAULT_MAX_CHUNK_CHARS = 8_000
DEFAULT_MAX_MEAN_CHUNK_CHARS = 3_000
DEFAULT_TOLERANCE_PCT = 5.0

# `author|title|lang`. A surrogate `works.id` would rot — `index --reset`
# reassigns every one of them (#193) — and no work's author or title
# contains a pipe (verified against the live index).
KEY_SEP = "|"


@dataclasses.dataclass(frozen=True)
class GranularityPolicy:
    max_chunk_chars: int
    max_mean_chunk_chars: int
    tolerance_pct: float
    known_coarse: dict[str, dict[str, int]]

    def ceiling(self, key: str, field: str, threshold: int) -> int:
        """Highest value *key* may report for *field* before failing.

        A baseline pinned to the exact measured value would fail on any
        edit that nudges a mean by one character, which is how a gate
        gets switched off. The tolerance is policy and lives in the
        manifest; the committed numbers stay the honest measurements.
        """

        allowed = self.known_coarse.get(key, {}).get(field)
        if allowed is None:
            return threshold
        return int(allowed * (1 + self.tolerance_pct / 100))


def make_key(author: str, title: str, lang: str) -> str:
    return KEY_SEP.join((author, title, lang))


def granularity_policy(manifest: dict[str, Any]) -> GranularityPolicy:
    raw = manifest.get("granularity") or {}
    known: dict[str, dict[str, int]] = {}
    for key, spec in (raw.get("known_coarse") or {}).items():
        if not isinstance(spec, dict):
            continue
        entry = {f: int(spec[f]) for f in ("max", "mean") if spec.get(f) is not None}
        if entry:
            known[str(key)] = entry
    return GranularityPolicy(
        max_chunk_chars=int(raw.get("max_chunk_chars") or DEFAULT_MAX_CHUNK_CHARS),
        max_mean_chunk_chars=int(
            raw.get("max_mean_chunk_chars") or DEFAULT_MAX_MEAN_CHUNK_CHARS
        ),
        tolerance_pct=float(
            raw.get("tolerance_pct")
            if raw.get("tolerance_pct") is not None
            else DEFAULT_TOLERANCE_PCT
        ),
        known_coarse=known,
    )


# Explicit joins rather than the `chunks_full` view: the view's
# `LEFT JOIN`s plus `LOWER(author)` make the planner scan, and this
# aggregate over 428k chunks took minutes through it against seconds here.
_MEASURE_SQL = """
SELECT w.author, w.title, c.lang,
       COUNT(*)                                  AS chunks,
       MAX(LENGTH(c.text))                       AS max_chars,
       CAST(ROUND(AVG(LENGTH(c.text))) AS INTEGER) AS mean_chars
  FROM chunks c
  LEFT JOIN editions     e ON e.id = c.edition_id
  LEFT JOIN translations t ON t.id = c.translation_id
  JOIN works w ON w.id = COALESCE(e.work_id, t.work_id)
 GROUP BY w.id, c.lang
HAVING MAX(LENGTH(c.text)) > ? OR AVG(LENGTH(c.text)) > ?
"""


def measure(
    conn: sqlite3.Connection,
    policy: GranularityPolicy,
) -> dict[str, dict[str, int]]:
    """Every work/lang pair exceeding either threshold, keyed naturally.

    Only the offenders are recorded. Snapshotting all 1,045 pairs would
    churn the committed file on every ordinary text edit, which is the
    other way a gate stops being read.
    """

    rows = conn.execute(
        _MEASURE_SQL, (policy.max_chunk_chars, policy.max_mean_chunk_chars)
    ).fetchall()
    return {
        make_key(r[0], r[1], r[2]): {
            "chunks": int(r[3]),
            "max": int(r[4]),
            "mean": int(r[5]),
        }
        for r in rows
    }


def build_snapshot(
    conn: sqlite3.Connection,
    manifest: dict[str, Any],
) -> dict[str, dict[str, int]]:
    return measure(conn, granularity_policy(manifest))


def load_snapshot(path: Path = SNAPSHOT_PATH) -> dict[str, dict[str, int]]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    return {
        str(k): {str(f): int(v) for f, v in (spec or {}).items()}
        for k, spec in (raw.get("pairs") or {}).items()
    }


def write_snapshot(
    snapshot: dict[str, dict[str, int]],
    path: Path = SNAPSHOT_PATH,
) -> None:
    payload = {
        "_comment": (
            "Generated by `make generate-authors` from data/index.sqlite. "
            "Per work/lang chunk-length measurements for every pair over a "
            "threshold in manifest.yaml's `granularity` block. Committed "
            "because the index is gitignored and CI would otherwise skip "
            "the granularity gate entirely (#176, same reason as #157). "
            "Do not hand-edit: refresh it after any ingest. A NEW key "
            "appearing here fails `make check-authors` until it is also "
            "added to `granularity.known_coarse` in manifest.yaml, which "
            "is the review step."
        ),
        "pairs": {k: dict(sorted(v.items())) for k, v in sorted(snapshot.items())},
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def validate_snapshot(
    snapshot: dict[str, dict[str, int]],
    manifest: dict[str, Any],
) -> list[str]:
    """Check measured granularity against the reviewed baseline. No DB.

    Three ways to fail, in the order they matter:

    1. A pair over a threshold that the baseline does not list — the new
       violation this gate exists to catch.
    2. A listed pair that got worse by more than the tolerance.
    3. A listed pair that no longer appears — it has been re-chunked
       (#176 part 2), so the entry is stale and must go. Without this the
       allowlist only ever grows, which is how `SKIP_RULES` would have
       rotted had #70 not added the same meta-check.
    """

    policy = granularity_policy(manifest)
    errors: list[str] = []
    for key in sorted(snapshot):
        got = snapshot[key]
        if key not in policy.known_coarse:
            errors.append(
                f"{key}: {got.get('chunks', 0):,} chunks, max "
                f"{got.get('max', 0):,} / mean {got.get('mean', 0):,} chars "
                f"exceeds the granularity thresholds "
                f"(max {policy.max_chunk_chars:,} / mean "
                f"{policy.max_mean_chunk_chars:,}) and is not in "
                f"granularity.known_coarse. Re-chunk the work, or add it to "
                f"the baseline in manifest.yaml with a note saying why its "
                f"coarseness is a real structural level."
            )
            continue
        for field, threshold in (
            ("max", policy.max_chunk_chars),
            ("mean", policy.max_mean_chunk_chars),
        ):
            value = got.get(field)
            if value is None:
                continue
            ceiling = policy.ceiling(key, field, threshold)
            if value > ceiling:
                errors.append(
                    f"{key}: {field} {value:,} chars is worse than its "
                    f"baseline ceiling {ceiling:,} — chunking regressed"
                )
    for key in sorted(set(policy.known_coarse) - set(snapshot)):
        errors.append(
            f"{key}: in granularity.known_coarse but no longer exceeds any "
            f"threshold — stale baseline entry, remove it from manifest.yaml"
        )
    return errors


def snapshot_drift(
    conn: sqlite3.Connection,
    manifest: dict[str, Any],
    snapshot: dict[str, dict[str, int]],
) -> list[str]:
    """Compare the committed snapshot against the live DB.

    Only runnable where the index exists, and the whole reason a stale
    snapshot cannot turn the CI check into a check of a fossil.
    """

    live = build_snapshot(conn, manifest)
    errors: list[str] = []
    for key in sorted(set(live) | set(snapshot)):
        want, got = live.get(key), snapshot.get(key)
        if want == got:
            continue
        errors.append(
            f"{key}: snapshot says {got or 'absent'} but DB has "
            f"{want or 'absent'} — run `make generate-authors`"
        )
    return errors
