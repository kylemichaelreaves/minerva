find_work = make_find_work(WORKS, case_insensitive=True)


def find_works(filename: str) -> list[CorpusWork]:
    """All Works claiming this filename. Used by the multi-CorpusWork-per-PDF
    code path; for the Hegel corpus we currently always return at most
    one entry, but the symmetric API keeps ``minerva.corpus.parse_dir``
    uniform across authors."""
    lower = filename.lower()
    return [w for w in WORKS if any(c.lower() == lower for c in w.filenames)]
